-- ---------------------------------------------------------------------------
-- 0. Pomocné funkce
-- ---------------------------------------------------------------------------

-- gen_random_uuid() je součástí pgcrypto, na hostovaném Supabase je už dostupné.
create extension if not exists pgcrypto with schema extensions;

-- ---------------------------------------------------------------------------
-- 1. Tabulky
-- ---------------------------------------------------------------------------

-- Jedna hra, kterou pc-agent sleduje (identifikovaná názvem procesu).
create table if not exists public.games (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(trim(name)) > 0),
  process_name text,
  created_at timestamptz not null default now()
);

comment on table public.games is 'Hry sledované pc-agentem (název + proces).';
comment on column public.games.process_name is 'Název spustitelného souboru, např. Cyberpunk2077.exe.';

-- Jedno hraní (herní seance) dané hry.
create table if not exists public.sessions (
  id uuid primary key default gen_random_uuid(),
  game_id uuid not null references public.games (id) on delete cascade,
  played_at timestamptz not null default now(),
  avg_fps numeric(7, 2) not null default 0 check (avg_fps >= 0),
  min_fps numeric(7, 2) not null default 0 check (min_fps >= 0),
  max_fps numeric(7, 2) not null default 0 check (max_fps >= 0),
  duration_seconds integer not null default 0 check (duration_seconds >= 0)
);

comment on table public.sessions is 'Jednotlivá hraní s agregovanými hodnotami FPS.';
comment on column public.sessions.played_at is 'Začátek seance (UTC).';
comment on column public.sessions.duration_seconds is 'Délka seance v sekundách.';

-- Časová řada FPS v rámci jedné seance.
create table if not exists public.fps_samples (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.sessions (id) on delete cascade,
  timestamp_offset numeric(10, 3) not null check (timestamp_offset >= 0),
  fps numeric(7, 2) not null check (fps >= 0)
);

comment on table public.fps_samples is 'Vzorky FPS v průběhu seance.';
comment on column public.fps_samples.timestamp_offset is 'Počet sekund od začátku seance.';
comment on column public.fps_samples.fps is 'Naměřené FPS v daném okamžiku.';

-- ---------------------------------------------------------------------------
-- 2. Indexy
-- ---------------------------------------------------------------------------

-- Jedna hra na jeden proces. Plný unikátní index (bez WHERE) povoluje více
-- ručně přidaných her bez procesu – NULL hodnoty se v UNIQUE indexu neporovnávají.
drop index if exists public.games_process_name_key;
create unique index if not exists games_process_name_key
  on public.games (process_name);

create index if not exists games_name_idx
  on public.games (lower(name));

create index if not exists sessions_game_id_played_at_idx
  on public.sessions (game_id, played_at desc);

-- Vzorky jsou v rámci seance unikátní podle času. Agent je před nahráním
-- maže a vkládá znovu, index je pojistka proti duplicitám. Kdyby v datech už
-- duplicity byly, index se nevytvoří (skript ale nespadne).
drop index if exists public.fps_samples_session_id_timestamp_offset_idx;

do $$
begin
  if exists (
    select 1
    from public.fps_samples
    group by session_id, timestamp_offset
    having count(*) > 1
  ) then
    raise notice 'fps_samples obsahuje duplicity, unikátní index se nevytváří.';
  else
    execute 'create unique index if not exists fps_samples_session_offset_key '
            'on public.fps_samples (session_id, timestamp_offset)';
  end if;
end
$$;

-- ---------------------------------------------------------------------------
-- 3. Row Level Security
-- ---------------------------------------------------------------------------

alter table public.games enable row level security;
alter table public.sessions enable row level security;
alter table public.fps_samples enable row level security;

-- Aplikace i agent používají publishable/anon klíč bez přihlášení, proto
-- politiky povolují plný přístup rolím anon a authenticated. Pokud později
-- přidáte Supabase Auth, nahraďte `using (true)` podmínkou na auth.uid().

-- games
drop policy if exists "games_select" on public.games;
create policy "games_select" on public.games
  for select to anon, authenticated
  using (true);

drop policy if exists "games_insert" on public.games;
create policy "games_insert" on public.games
  for insert to anon, authenticated
  with check (true);

drop policy if exists "games_update" on public.games;
create policy "games_update" on public.games
  for update to anon, authenticated
  using (true) with check (true);

drop policy if exists "games_delete" on public.games;
create policy "games_delete" on public.games
  for delete to anon, authenticated
  using (true);

-- sessions
drop policy if exists "sessions_select" on public.sessions;
create policy "sessions_select" on public.sessions
  for select to anon, authenticated
  using (true);

drop policy if exists "sessions_insert" on public.sessions;
create policy "sessions_insert" on public.sessions
  for insert to anon, authenticated
  with check (true);

drop policy if exists "sessions_update" on public.sessions;
create policy "sessions_update" on public.sessions
  for update to anon, authenticated
  using (true) with check (true);

drop policy if exists "sessions_delete" on public.sessions;
create policy "sessions_delete" on public.sessions
  for delete to anon, authenticated
  using (true);

-- fps_samples
drop policy if exists "fps_samples_select" on public.fps_samples;
create policy "fps_samples_select" on public.fps_samples
  for select to anon, authenticated
  using (true);

drop policy if exists "fps_samples_insert" on public.fps_samples;
create policy "fps_samples_insert" on public.fps_samples
  for insert to anon, authenticated
  with check (true);

drop policy if exists "fps_samples_update" on public.fps_samples;
create policy "fps_samples_update" on public.fps_samples
  for update to anon, authenticated
  using (true) with check (true);

drop policy if exists "fps_samples_delete" on public.fps_samples;
create policy "fps_samples_delete" on public.fps_samples
  for delete to anon, authenticated
  using (true);

-- ---------------------------------------------------------------------------
-- 4. Grants
-- ---------------------------------------------------------------------------

-- Hostované projekty je mají ve výchozím stavu, ale Supabase je postupně
-- dělá opt-in. Explicitní grant nic nerozbije a chrání před chybou
-- "permission denied for table ...".
grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.games to anon, authenticated;
grant select, insert, update, delete on public.sessions to anon, authenticated;
grant select, insert, update, delete on public.fps_samples to anon, authenticated;

-- Identity sloupec fps_samples.id potřebuje sekvenci.
grant usage, select on all sequences in schema public to anon, authenticated;

