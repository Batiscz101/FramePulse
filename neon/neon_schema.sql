grant select, insert, update, delete on public.fps_samples to anonymous, authenticated;
grant select, insert, update, delete on public.live_status to anonymous, authenticated;

-- The Identity column fps_samples.id needs a sequence.
grant usage, select on all sequences in schema public to anonymous, authenticated;

